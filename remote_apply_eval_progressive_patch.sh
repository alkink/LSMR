#!/usr/bin/env bash
set -euo pipefail

# Usage:
#   bash remote_apply_eval_progressive_patch.sh /path/to/LSMR
# If path is omitted, current directory is used.

ROOT_DIR="${1:-.}"
TARGET="${ROOT_DIR%/}/eval_progressive.sh"

cat > "$TARGET" <<'EOF'
#!/bin/bash
# Parametrik CULane evaluation — progressive scaling için
# Kullanım: bash eval_progressive.sh <config_name> <iter>
# Örnek:    bash eval_progressive.sh LSTR_CULANE_100_baseline 800

# Güvenli shell ayarları
set -euo pipefail

CONFIG=${1:-"LSTR_CULANE_100_baseline"}
ITER=${2:-"800"}

root="../results/${CONFIG}"
data_dir="../../CULane/"
split="testing"
detect_dir="${root}/${ITER}/${split}"
w_lane=30
iou=0.5
im_w=1640
im_h=590
frame=1
list="${data_dir}list/test.txt"
out="${root}/${ITER}_iou${iou}.txt"

echo "Config    : ${CONFIG}"
echo "Iteration : ${ITER}"
echo "detect_dir: ${detect_dir}"
echo "Output    : ${out}"
echo ""

cd lane_evaluation_main

# OpenCV shared library eksikse binary'yi bulunduğu sunucuda yeniden derle.
if [ ! -x ./evaluate ]; then
    echo "[eval_progressive] evaluate binary yok, derleniyor..."
    make -j"$(nproc)"
fi

if ldd ./evaluate | grep -q "not found"; then
    echo "[eval_progressive] Eksik paylaşımlı kütüphane bulundu, evaluate binary yeniden derleniyor..."

    # Conda opencv4.pc varsa pkg-config'in bulabilmesi için yolu ekle.
    if [ -n "${CONDA_PREFIX:-}" ] && [ -d "${CONDA_PREFIX}/lib/pkgconfig" ]; then
        export PKG_CONFIG_PATH="${CONDA_PREFIX}/lib/pkgconfig:${PKG_CONFIG_PATH:-}"
    fi

    if ! command -v pkg-config >/dev/null 2>&1 || ! pkg-config --exists opencv4; then
        echo "[eval_progressive][HATA] opencv4 geliştirme dosyaları bulunamadı."
        echo "Kurulum (apt): sudo apt-get update && sudo apt-get install -y build-essential pkg-config libopencv-dev"
        echo "Alternatif (conda): conda install -n clrernet -c conda-forge pkg-config opencv=4.6.0"
        echo "Gerekirse: export PKG_CONFIG_PATH=\"$CONDA_PREFIX/lib/pkgconfig:${PKG_CONFIG_PATH:-}\""
        echo "Sonra: export LD_LIBRARY_PATH=\"$CONDA_PREFIX/lib:${LD_LIBRARY_PATH:-}\""
        exit 1
    fi
    make clean
    make -j"$(nproc)"
fi

# Bazı uzak sunucularda OpenCV conda env içinden geliyor olabilir.
if ldd ./evaluate | grep -q "not found"; then
    if [ -n "${CONDA_PREFIX:-}" ] && [ -d "${CONDA_PREFIX}/lib" ]; then
        export LD_LIBRARY_PATH="${CONDA_PREFIX}/lib:${LD_LIBRARY_PATH:-}"
    fi
fi

if ldd ./evaluate | grep -q "not found"; then
    echo "[eval_progressive][HATA] evaluate hâlâ eksik shared library ile bağlı:"
    ldd ./evaluate | grep "not found" || true
    exit 1
fi

./evaluate -a $data_dir -d $detect_dir -i $data_dir -l $list -w $w_lane -t $iou -c $im_w -r $im_h -f $frame -o $out

# Add FPS to the output file if it was generated by the python script
if [ -f "$detect_dir/fps.txt" ]; then
    cat "$detect_dir/fps.txt" >> "$out"
fi

echo ""
echo "F1 sonucu: ${out}"
cat "${out}"
EOF

chmod +x "$TARGET"
echo "Patched: $TARGET"
